using System.Collections.Generic;
using System.Linq;

namespace SixLabors.ImageSharp.SourceGenerators.Tests;

/// <summary>
/// Writes <c>PixelOperationsTests.Specialized.Generated.cs</c>: a test class for the specialized
/// <c>PixelOperations</c> of each pixel type. Ported from the T4 template it replaced,
/// <c>tests/ImageSharp.Tests/PixelFormats/PixelOperations/Generated/PixelOperationsTests.Specialized.Generated.tt</c>
/// with its <c>_Common.ttinclude</c>. These lists differ from the library's
/// <see cref="Names.PixelTypeNames"/>, so they stay here.
/// </summary>
internal sealed class PixelOperationsTestsEmitter : IEmitter
{
    private static readonly string[] UnassociatedAlphaPixelTypes =
    [
        "A8",
        "Argb32",
        "Abgr32",
        "Bgra32",
        "Bgra4444",
        "Bgra5551",
        "Byte4",
        "HalfVector4",
        "La16",
        "La32",
        "NormalizedByte4",
        "NormalizedShort4",
        "Rgba1010102",
        "Rgba32",
        "Rgba64",
        "RgbaVector",
        "Short4",
    ];

    private static readonly string[] CommonPixelTypes =
    [
        "A8",
        "Argb32",
        "Abgr32",
        "Bgr24",
        "Bgr565",
        "Bgra32",
        "Bgra4444",
        "Bgra5551",
        "Byte4",
        "HalfSingle",
        "HalfVector2",
        "HalfVector4",
        "L16",
        "L8",
        "La16",
        "La32",
        "NormalizedByte2",
        "NormalizedByte4",
        "NormalizedShort2",
        "NormalizedShort4",
        "Rg32",
        "Rgb24",
        "Rgb48",
        "Rgba1010102",
        "Rgba32",
        "Rgba64",
        "RgbaVector",
        "Short2",
        "Short4",
    ];

    /// <inheritdoc/>
    public IReadOnlyList<GeneratedFile> Files { get; } = [new("PixelOperationsTests.Specialized.Generated.cs", Emit)];

    private static void Emit(SourceWriter writer)
    {
        writer.WriteLine("""
            // Copyright (c) Six Labors.
            // Licensed under the Apache License, Version 2.0.

            // <auto-generated />

            using SixLabors.ImageSharp.PixelFormats;
            using Xunit;


            namespace SixLabors.ImageSharp.Tests.PixelFormats.PixelOperations;

            public partial class PixelOperationsTests
            {
            """);

        using (writer.Indent())
        {
            foreach (string pixelType in CommonPixelTypes)
            {
                string alpha = UnassociatedAlphaPixelTypes.Contains(pixelType)
                    ? "PixelAlphaRepresentation.Unassociated"
                    : "PixelAlphaRepresentation.None";

                EmitSpecializedClass(pixelType, alpha, writer);
            }
        }

        writer.WriteLine("}");
        writer.WriteLine();
    }

    private static void EmitSpecializedClass(string pixelType, string alpha, SourceWriter writer)
    {
        writer.WriteLine($$"""
            public partial class {{pixelType}}_OperationsTests : PixelOperationsTests<{{pixelType}}>
            {
                public {{pixelType}}_OperationsTests(ITestOutputHelper output)
                    : base(output)
                {
                }

                protected override PixelOperations<{{pixelType}}> Operations => {{pixelType}}.PixelOperations.Instance;

                [Fact]
                public void IsSpecialImplementation() => Assert.IsType<{{pixelType}}.PixelOperations>(PixelOperations<{{pixelType}}>.Instance);

                [Fact]
                public void PixelTypeInfoHasCorrectAlphaRepresentation()
                {
                    var alphaRepresentation = this.Operations.GetPixelTypeInfo().AlphaRepresentation;
                    Assert.Equal({{alpha}}, alphaRepresentation);
                }
            }
            """);
    }
}
