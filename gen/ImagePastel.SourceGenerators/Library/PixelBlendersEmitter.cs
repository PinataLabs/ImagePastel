                {
                    source.W *= opacity;

                    return Clear(backdrop, source);
                }
            """);

    private static void EmitPixelFunction(string blender, string composer, SourceWriter writer)
        => writer.WriteLine($$"""

                /// <summary>
                /// Returns the result of the "{{blender}}{{composer}}" compositing equation.
                /// </summary>
                /// <typeparam name="TPixel">The pixel format.</typeparam>
                /// <param name="backdrop">The backdrop vector.</param>
                /// <param name="source">The source vector.</param>
                /// <param name="opacity">The source opacity. Range 0..1</param>
                /// <returns>The <typeparamref name="TPixel"/>.</returns>
                [MethodImpl(MethodImplOptions.AggressiveInlining)]
                public static TPixel {{blender}}{{composer}}<TPixel>(TPixel backdrop, TPixel source, float opacity)
                    where TPixel : unmanaged, IPixel<TPixel>
                {
                    opacity = Numerics.Clamp(opacity, 0, 1);
                    TPixel dest = default;
                    dest.FromScaledVector4({{blender}}{{composer}}(backdrop.ToScaledVector4(), source.ToScaledVector4(), opacity));
                    return dest;
                }

            """);

    private static void EmitDefaultPixelBlenders(SourceWriter writer)
    {
        writer.WriteLine("""
            // Copyright (c) Six Labors.
            // Licensed under the Apache License, Version 2.0.

            // <auto-generated />
            using System;
            using System.Numerics;

            namespace PinataLabs.ImagePastel.PixelFormats.PixelBlenders;

            /// <summary>
            /// Collection of Porter Duff alpha blending functions applying different composition models.
            /// </summary>
            /// <remarks>
            /// These functions are designed to be a general solution for all color cases,
            /// that is, they take in account the alpha value of both the backdrop
            /// and source, and there's no need to alpha-premultiply neither the backdrop
            /// nor the source.
            /// Note there are faster functions for when the backdrop color is known
            /// to be opaque
            /// </remarks>
            internal static class DefaultPixelBlenders<TPixel>
                where TPixel : unmanaged, IPixel<TPixel>
            {

            """);

        // The template indents the nested classes by two levels.
        using (writer.Indent())
        using (writer.Indent())
        {
            foreach (string composer in PixelBlenderNames.Composers)
            {
                foreach (string blender in PixelBlenderNames.Blenders)
                {
                    string name = blender + composer;
                    writer.WriteLine($$"""
                        /// <summary>
                        /// A pixel blender that implements the "{{name}}" composition equation.
                        /// </summary>
                        public class {{name}} : PixelBlender<TPixel>
                        {
                            /// <summary>
                            /// Gets the static instance of this blender.
                            /// </summary>
                            public static {{name}} Instance { get; } = new {{name}}();

                            /// <inheritdoc />
                            public override TPixel Blend(TPixel background, TPixel source, float amount)
                            {
                                TPixel dest = default;
                                dest.FromScaledVector4(PorterDuffFunctions.{{name}}(background.ToScaledVector4(), source.ToScaledVector4(), Numerics.Clamp(amount, 0, 1)));
                                return dest;
                            }

                            /// <inheritdoc />
                            protected override void BlendFunction(Span<Vector4> destination, ReadOnlySpan<Vector4> background, ReadOnlySpan<Vector4> source, float amount)
                            {
                                amount = Numerics.Clamp(amount, 0, 1);
                                for (int i = 0; i < destination.Length; i++)
                                {
                                    destination[i] = PorterDuffFunctions.{{name}}(background[i], source[i], amount);
                                }
                            }

                            /// <inheritdoc />
                            protected override void BlendFunction(Span<Vector4> destination, ReadOnlySpan<Vector4> background, ReadOnlySpan<Vector4> source, ReadOnlySpan<float> amount)
                            {
                                for (int i = 0; i < destination.Length; i++)
                                {
                                    destination[i] = PorterDuffFunctions.{{name}}(background[i], source[i], Numerics.Clamp(amount[i], 0, 1));
                                }
                            }
                        }

                        """);
                }
            }
        }

        writer.WriteLine("}");
    }
}
