using System.Collections.Generic;
using System.Linq;
using PinataLabs.ImagePastel.SourceGenerators.Names;

namespace PinataLabs.ImagePastel.SourceGenerators.Library;

/// <summary>
/// Writes the pixel operations: <c>&lt;Pixel&gt;.PixelOperations.Generated.cs</c>, the optimized bulk
/// conversions of each common pixel type, and <c>PixelOperations{TPixel}.Generated.cs</c>, the
/// generic conversions to and from each of them. Ported from the T4 templates they replaced,
/// <c>PixelFormats/PixelImplementations/PixelOperations/Generated/*.PixelOperations.Generated.tt</c>
/// with their <c>_Common.ttinclude</c>, and <c>PixelFormats/PixelOperations{TPixel}.Generated.tt</c>.
/// </summary>
internal sealed class PixelOperationsEmitter : IEmitter
{
    /// <inheritdoc/>
    public IReadOnlyList<GeneratedFile> Files { get; } =
    [
        .. PixelTypeNames.CommonPixelTypes.Select(
            pixelType => new GeneratedFile(pixelType + ".PixelOperations.Generated.cs", writer => EmitPixel(pixelType, writer))),
        new("PixelOperations{TPixel}.Generated.cs", EmitGeneric),
    ];

    private static void EmitPixel(string pixelType, SourceWriter writer)
    {
        writer.WriteLine($$"""
            // Copyright (c) Six Labors.
            // Licensed under the Apache License, Version 2.0.

            // <auto-generated />

            using System;
            using System.Numerics;
            using System.Runtime.CompilerServices;
            using System.Runtime.InteropServices;
            using PinataLabs.ImagePastel.PixelFormats.Utils;

            namespace PinataLabs.ImagePastel.PixelFormats;

            /// <content>
            /// Provides optimized overrides for bulk operations.
            /// </content>
            public partial struct {{pixelType}}
            {
                /// <summary>
                /// Provides optimized overrides for bulk operations.
                /// </summary>
                internal partial class PixelOperations : PixelOperations<{{pixelType}}>
                {
            """);

        using (writer.Indent())
        using (writer.Indent())
        {
            EmitAllDefaultConversionMethods(pixelType, writer);
        }

        writer.WriteLine("""
                }
            }
            """);
    }

    private static void EmitAllDefaultConversionMethods(string pixelType, SourceWriter writer)
    {
        EmitDefaultSelfConversionMethods(pixelType, writer);

        if (PixelTypeNames.Rgba32CompatibleTypes.Contains(pixelType))
        {
            EmitRgba32CompatibleVector4ConversionMethods(pixelType, pixelType.EndsWith("32"), writer);
        }

        IEnumerable<string> optimizedDestTypes = PixelTypeNames.OptimizedPixelTypes.Contains(pixelType)
            ? PixelTypeNames.OptimizedPixelTypes.Where(p => p != pixelType)
            : [];

        foreach (string destPixelType in optimizedDestTypes)
        {
            EmitOptimizedConversionMethods(pixelType, destPixelType, writer);
        }

        IEnumerable<string> otherDestTypes = PixelTypeNames.CommonPixelTypes
            .Where(p => p != pixelType)
            .Except(optimizedDestTypes);

        foreach (string destPixelType in otherDestTypes)
        {
            EmitDefaultConvertToMethod(pixelType, destPixelType, writer);
        }

        EmitGenericConverterMethods(pixelType, writer);
    }

    private static void EmitGenericConverterMethods(string pixelType, SourceWriter writer)
    {
        writer.WriteLine($$"""
            /// <inheritdoc />
            public override void From<TSourcePixel>(
                Configuration configuration,
                ReadOnlySpan<TSourcePixel> sourcePixels,
                Span<{{pixelType}}> destinationPixels)
            {
                PixelOperations<TSourcePixel>.Instance.To{{pixelType}}(configuration, sourcePixels, destinationPixels.Slice(0, sourcePixels.Length));
            }

            """);
    }

    private static void EmitDefaultSelfConversionMethods(string pixelType, SourceWriter writer)
    {
        writer.WriteLine($$"""
            /// <inheritdoc />
            public override void From{{pixelType}}(Configuration configuration, ReadOnlySpan<{{pixelType}}> source, Span<{{pixelType}}> destinationPixels)
            {
                Guard.NotNull(configuration, nameof(configuration));
                Guard.DestinationShouldNotBeTooShort(source, destinationPixels, nameof(destinationPixels));

                source.CopyTo(destinationPixels.Slice(0, source.Length));
            }

            /// <inheritdoc />
            public override void To{{pixelType}}(Configuration configuration, ReadOnlySpan<{{pixelType}}> sourcePixels, Span<{{pixelType}}> destinationPixels)
            {
                Guard.NotNull(configuration, nameof(configuration));
                Guard.DestinationShouldNotBeTooShort(sourcePixels, destinationPixels, nameof(destinationPixels));

                sourcePixels.CopyTo(destinationPixels.Slice(0, sourcePixels.Length));
            }
            """);
    }

    private static void EmitDefaultConvertToMethod(string fromPixelType, string toPixelType, SourceWriter writer)
    {
        writer.WriteLine($$"""
            /// <inheritdoc />
            public override void To{{toPixelType}}(
                Configuration configuration,
                ReadOnlySpan<{{fromPixelType}}> sourcePixels,
                Span<{{toPixelType}}> destinationPixels)
            {
                Guard.NotNull(configuration, nameof(configuration));
                Guard.DestinationShouldNotBeTooShort(sourcePixels, destinationPixels, nameof(destinationPixels));

                ref {{fromPixelType}} sourceRef = ref MemoryMarshal.GetReference(sourcePixels);
                ref {{toPixelType}} destRef = ref MemoryMarshal.GetReference(destinationPixels);

                for (nint i = 0; i < sourcePixels.Length; i++)
                {
                    ref {{fromPixelType}} sp = ref Unsafe.Add(ref sourceRef, i);
                    ref {{toPixelType}} dp = ref Unsafe.Add(ref destRef, i);

                    dp.From{{fromPixelType}}(sp);
                }
            }
            """);
    }

    private static void EmitOptimizedConversionMethods(string thisPixelType, string otherPixelType, SourceWriter writer)
    {
        writer.WriteLine($$"""
            /// <inheritdoc />
            public override void To{{otherPixelType}}(
                Configuration configuration,
                ReadOnlySpan<{{thisPixelType}}> sourcePixels,
                Span<{{otherPixelType}}> destinationPixels)
            {
                Guard.NotNull(configuration, nameof(configuration));
                Guard.DestinationShouldNotBeTooShort(sourcePixels, destinationPixels, nameof(destinationPixels));

                ReadOnlySpan<byte> source = MemoryMarshal.Cast<{{thisPixelType}}, byte>(sourcePixels);
                Span<byte> dest = MemoryMarshal.Cast<{{otherPixelType}}, byte>(destinationPixels);
                PixelConverter.From{{thisPixelType}}.To{{otherPixelType}}(source, dest);
            }

            /// <inheritdoc />
            public override void From{{otherPixelType}}(
                Configuration configuration,
                ReadOnlySpan<{{otherPixelType}}> sourcePixels,
                Span<{{thisPixelType}}> destinationPixels)
            {
                Guard.NotNull(configuration, nameof(configuration));
                Guard.DestinationShouldNotBeTooShort(sourcePixels, destinationPixels, nameof(destinationPixels));

                ReadOnlySpan<byte> source = MemoryMarshal.Cast<{{otherPixelType}}, byte>(sourcePixels);
                Span<byte> dest = MemoryMarshal.Cast<{{thisPixelType}}, byte>(destinationPixels);
                PixelConverter.From{{otherPixelType}}.To{{thisPixelType}}(source, dest);
            }
            """);
    }

    private static void EmitRgba32CompatibleVector4ConversionMethods(string pixelType, bool hasAlpha, SourceWriter writer)
    {
        string removeTheseModifiers = "PixelConversionModifiers.Scale";
        if (!hasAlpha)
        {
            removeTheseModifiers += " | PixelConversionModifiers.Premultiply";
        }

        writer.WriteLine($$"""
            /// <inheritdoc />
            public override void FromVector4Destructive(
                Configuration configuration,
                Span<Vector4> sourceVectors,
                Span<{{pixelType}}> destinationPixels,
                PixelConversionModifiers modifiers)
            {
                Vector4Converters.RgbaCompatible.FromVector4(configuration, this, sourceVectors, destinationPixels, modifiers.Remove({{removeTheseModifiers}}));
            }

            /// <inheritdoc />
            public override void ToVector4(
                Configuration configuration,
                ReadOnlySpan<{{pixelType}}> sourcePixels,
                Span<Vector4> destVectors,
                PixelConversionModifiers modifiers)
            {
                Vector4Converters.RgbaCompatible.ToVector4(configuration, this, sourcePixels, destVectors, modifiers.Remove({{removeTheseModifiers}}));
            }
            """);
    }

    private static void EmitGeneric(SourceWriter writer)
    {
        writer.WriteLine("""
            // Copyright (c) Six Labors.
            // Licensed under the Apache License, Version 2.0.
            // <auto-generated />

            using System;
            using System.Runtime.CompilerServices;
            using System.Runtime.InteropServices;

            namespace PinataLabs.ImagePastel.PixelFormats;

            public partial class PixelOperations<TPixel>
            {
            """);

        using (writer.Indent())
        {
            for (int i = 0; i < PixelTypeNames.CommonPixelTypes.Length; i++)
            {
                if (i > 0)
                {
                    writer.WriteLine();
                }

                string pixelType = PixelTypeNames.CommonPixelTypes[i];
                EmitFromMethods(pixelType, writer);
                EmitToDestFormatMethods(pixelType, writer);
            }
        }

        writer.WriteLine("}");
    }

    private static void EmitFromMethods(string pixelType, SourceWriter writer)
    {
        writer.WriteLine($$"""
            /// <summary>
            /// Converts all pixels in 'source` span of <see cref="{{pixelType}}"/> into a span of <typeparamref name="TPixel"/>-s.
            /// </summary>
            /// <param name="configuration">A <see cref="Configuration"/> to configure internal operations.</param>
            /// <param name="source">The source <see cref="Span{T}"/> of <see cref="{{pixelType}}"/> data.</param>
            /// <param name="destinationPixels">The <see cref="Span{T}"/> to the destination pixels.</param>
            public virtual void From{{pixelType}}(Configuration configuration, ReadOnlySpan<{{pixelType}}> source, Span<TPixel> destinationPixels)
            {
                Guard.DestinationShouldNotBeTooShort(source, destinationPixels, nameof(destinationPixels));
            """);

        // The template has a line of eight spaces here. With the indentation above, this writes it.
        writer.WriteLine("    ");

        writer.WriteLine($$"""
                ref {{pixelType}} sourceBaseRef = ref MemoryMarshal.GetReference(source);
                ref TPixel destBaseRef = ref MemoryMarshal.GetReference(destinationPixels);

                for (int i = 0; i < source.Length; i++)
                {
                    ref {{pixelType}} sp = ref Unsafe.Add(ref sourceBaseRef, i);
                    ref TPixel dp = ref Unsafe.Add(ref destBaseRef, i);

                    dp.From{{pixelType}}(sp);
                }
            }

            /// <summary>
            /// A helper for <see cref="From{{pixelType}}(Configuration, ReadOnlySpan{{{pixelType}}}, Span{TPixel})"/> that expects a byte span.
            /// The layout of the data in 'sourceBytes' must be compatible with <see cref="{{pixelType}}"/> layout.
            /// </summary>
            /// <param name="configuration">A <see cref="Configuration"/> to configure internal operations.</param>
            /// <param name="sourceBytes">The <see cref="ReadOnlySpan{T}"/> to the source bytes.</param>
            /// <param name="destinationPixels">The <see cref="Span{T}"/> to the destination pixels.</param>
            /// <param name="count">The number of pixels to convert.</param>
            [MethodImpl(MethodImplOptions.AggressiveInlining)]
            public void From{{pixelType}}Bytes(Configuration configuration, ReadOnlySpan<byte> sourceBytes, Span<TPixel> destinationPixels, int count)
            {
                this.From{{pixelType}}(configuration, MemoryMarshal.Cast<byte, {{pixelType}}>(sourceBytes).Slice(0, count), destinationPixels);
            }

            """);
    }

    private static void EmitToDestFormatMethods(string pixelType, SourceWriter writer)
    {
        writer.WriteLine($$"""
            /// <summary>
            /// Converts all pixels of the 'sourcePixels` span to a span of <see cref="{{pixelType}}"/>-s.
            /// </summary>
            /// <param name="configuration">A <see cref="Configuration"/> to configure internal operations</param>
            /// <param name="sourcePixels">The span of source pixels</param>
            /// <param name="destinationPixels">The destination span of <see cref="{{pixelType}}"/> data.</param>
            public virtual void To{{pixelType}}(Configuration configuration, ReadOnlySpan<TPixel> sourcePixels, Span<{{pixelType}}> destinationPixels)
            {
                Guard.DestinationShouldNotBeTooShort(sourcePixels, destinationPixels, nameof(destinationPixels));

                ref TPixel sourceBaseRef = ref MemoryMarshal.GetReference(sourcePixels);
                ref {{pixelType}} destBaseRef = ref MemoryMarshal.GetReference(destinationPixels);

                for (int i = 0; i < sourcePixels.Length; i++)
                {
                    ref TPixel sp = ref Unsafe.Add(ref sourceBaseRef, i);
                    ref {{pixelType}} dp = ref Unsafe.Add(ref destBaseRef, i);

                    dp.FromScaledVector4(sp.ToScaledVector4());
                }
            }

            /// <summary>
            /// A helper for <see cref="To{{pixelType}}(Configuration, ReadOnlySpan{TPixel}, Span{{{pixelType}}})"/> that expects a byte span as destination.
            /// The layout of the data in 'destBytes' must be compatible with <see cref="{{pixelType}}"/> layout.
            /// </summary>
            /// <param name="configuration">A <see cref="Configuration"/> to configure internal operations</param>
            /// <param name="sourcePixels">The <see cref="Span{T}"/> to the source pixels.</param>
            /// <param name="destBytes">The <see cref="Span{T}"/> to the destination bytes.</param>
            /// <param name="count">The number of pixels to convert.</param>
            [MethodImpl(MethodImplOptions.AggressiveInlining)]
            public void To{{pixelType}}Bytes(Configuration configuration, ReadOnlySpan<TPixel> sourcePixels, Span<byte> destBytes, int count)
            {
                this.To{{pixelType}}(configuration, sourcePixels.Slice(0, count), MemoryMarshal.Cast<byte, {{pixelType}}>(destBytes));
            }
            """);
    }
}
